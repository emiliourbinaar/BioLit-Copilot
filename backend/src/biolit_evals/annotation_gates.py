"""Score the annotated blind sheet and run both gates.

Reads the markdown sheet the annotator filled in, joins it back to the frozen corpus, and
runs `evaluate_gate1` (tractability, over all 30) and `evaluate_gate2` (stop rule, over the
15 contradiction pairs only). The two gates read different subsets and have different `n` by
design.

WHY THIS WRITES A COMMITTED ARTIFACT. The sheet itself lives under gitignored `data/` because
it carries full abstract text. The annotator's LABELS carry none, and they are the most
expensive input in Phase 5 -- hand judgement that cannot be regenerated by re-running
anything. `--labels-out` writes them, plus the gold label each is being compared against, as
a committed record so every downstream number stays reproducible from the repository alone.

Also records which endpoint the sheet displayed for each pair. That is not decoration: the
blind protocol shows exactly one of the pair's two endpoints, chosen at random, so on a
disease-shown row the annotator is not told WHICH chemical the pair turns on. Whether that
depresses agreement is a question about the protocol rather than about the proxy, and it can
only be asked if the shown endpoint is recorded alongside the verdict.

`main()` only; per this project's convention it gets no direct unit test, and every function
it calls is tested in its own module.
"""

import argparse
import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from biolit_evals._meta import git_sha
from biolit_evals.annotation_export import (
    DEFAULT_CORPUS,
    DEFAULT_MARKDOWN,
    DEFAULT_SHEET,
    evaluate_gate1,
    evaluate_gate2,
    parse_annotations,
)

DEFAULT_LABELS_OUT = "evals/gold/annotation_batch_1_labels.jsonl"
DEFAULT_LOG = "evals/annotation_runs.jsonl"
GATE2_LABEL = "contradiction"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Run Gate 1 and Gate 2 on an annotated batch.")
    parser.add_argument("--markdown", default=DEFAULT_MARKDOWN)
    parser.add_argument("--sheet", default=DEFAULT_SHEET)
    parser.add_argument("--corpus", default=DEFAULT_CORPUS)
    parser.add_argument("--labels-out", default=DEFAULT_LABELS_OUT)
    parser.add_argument("--log", default=DEFAULT_LOG)
    args = parser.parse_args(argv)

    annotations = parse_annotations(Path(args.markdown).read_text(encoding="utf-8"))

    gold = {}
    for line in Path(args.corpus).read_text(encoding="utf-8").splitlines():
        if line.strip():
            record = json.loads(line)
            gold[f"{record['paper_id_a']}_{record['paper_id_b']}"] = record

    shown = {
        row["pair_id"]: row["shared_concept_id"]
        for row in json.loads(Path(args.sheet).read_text(encoding="utf-8"))
    }

    missing = sorted(set(annotations) - set(gold))
    if missing:
        raise ValueError(f"annotated pairs absent from the corpus manifest: {missing}")

    rows = []
    for pair_id, annotation in annotations.items():
        record = gold[pair_id]
        concept = shown.get(pair_id)
        rows.append(
            {
                "pair_id": pair_id,
                "gold_label": record["label"],
                "annotator_label": annotation.label,
                "shown_concept_id": concept,
                # Which endpoint the annotator actually saw. Recorded because the blind
                # protocol hides the other one, and that may itself cost agreement.
                "shown_endpoint": "chemical" if concept == record["chemical_id"] else "disease",
                "reason": annotation.reason,
            }
        )
    rows.sort(key=lambda r: r["pair_id"])
    Path(args.labels_out).write_text(
        "".join(json.dumps(r, sort_keys=True) + "\n" for r in rows), encoding="utf-8"
    )

    cant_tell = sum(1 for r in rows if r["annotator_label"] == "cant_tell")
    gate1 = evaluate_gate1(cant_tell=cant_tell, n=len(rows))

    contradiction_rows = [r for r in rows if r["gold_label"] == GATE2_LABEL]
    genuine = sum(1 for r in contradiction_rows if r["annotator_label"] == GATE2_LABEL)
    gate2 = evaluate_gate2(genuine=genuine, n=len(contradiction_rows))

    confusion = Counter((r["gold_label"], r["annotator_label"]) for r in rows)
    exact = sum(1 for r in rows if r["gold_label"] == r["annotator_label"])

    entry = {
        "timestamp": datetime.now(UTC).isoformat(),
        "git_sha": git_sha(),
        "step": "annotation_gates",
        "batch": Path(args.markdown).name,
        "corpus_manifest": args.corpus,
        "n_annotated": len(rows),
        "gold_composition": dict(Counter(r["gold_label"] for r in rows)),
        "annotator_composition": dict(Counter(r["annotator_label"] for r in rows)),
        "exact_agreement": exact,
        "gate1": {
            "cant_tell": gate1.cant_tell,
            "n": gate1.n,
            "verdict": gate1.verdict,
            "interval": list(gate1.interval),
        },
        "gate2": {
            "genuine": gate2.genuine,
            "n": gate2.n,
            "verdict": gate2.verdict,
            "interval": list(gate2.interval),
        },
        "confusion": {f"{g}->{a}": c for (g, a), c in sorted(confusion.items())},
    }
    with Path(args.log).open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(entry) + "\n")

    print(f"wrote {args.labels_out}: {len(rows)} annotated pairs")
    print(f"exact agreement with gold: {exact}/{len(rows)}")
    print(f"GATE 1 (tractability, n={gate1.n}): cant_tell={gate1.cant_tell} -> {gate1.verdict}")
    print(f"GATE 2 (stop rule,    n={gate2.n}): genuine={gate2.genuine} -> {gate2.verdict}")
    lo, hi = gate2.interval
    print(
        f"  pi-hat = {genuine}/{gate2.n} = {genuine / gate2.n:.4f}, 95% Wilson [{lo:.4f}, {hi:.4f}]"
    )


if __name__ == "__main__":
    main()
